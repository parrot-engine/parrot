double sin(double x) {
    size_t index = (size_t)round((x * SINE_LENGTH * 2) / M_PI) % (SINE_LENGTH * 4);

    if (index == SINE_LENGTH) {
        return 1;
    }

    bool flip = false;
    if (index > 0) {
        if (index > SINE_LENGTH * 2) {
            index -= SINE_LENGTH * 2;
            flip = true;
        }

        if (index > SINE_LENGTH) {
            index = (SINE_LENGTH * 2) - index;
        }
    }

    double value = sine_table[index];
    if (flip) {
        value = -value;
    }
    return value;
}